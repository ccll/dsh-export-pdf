import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const repositoryRoot = dirname(dirname(fileURLToPath(import.meta.url)))
/** 浏览器半区按此顺序拼接：纯数据函数在前，React 组件与插件入口在后。 */
export const CLIENT_FRAGMENTS = ['src/naming.mjs', 'src/view-state.mjs', 'src/view.mjs', 'src/client.mjs']
/** 宿主模块系统按包名加载客户端 bundle，id 必须与 package.json 的 name 一致。 */
const PACKAGE_NAME = 'dsh-export-pdf'

/**
 * 生成浏览器 bundle 文本。宿主不提供前端构建链，这里只做三件事：
 * 去掉 ESM 的 `export` 前缀、按固定顺序拼接、套上模块加载器工厂包装。
 * @returns {Promise<string>}
 */
export async function clientBundle() {
  let fragments = ''
  for (const relative of CLIENT_FRAGMENTS) {
    const source = await readFile(join(repositoryRoot, relative), 'utf8')
    fragments += `${source.replace(/^export\s+/gm, '')}\n`
  }
  return `/* Generated by scripts/build-client.mjs; edit src/ instead. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PACKAGE_NAME)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    const React = require("react");
${fragments}
    exports.apply = apply;
    exports.inject = inject;
    exports.name = name;
    return module.exports;
  }
});
`
}

/**
 * 写入 `.dsh-plugin/client.js`。临时文件 + 原子 rename，HTTP 读取或
 * 并发构建只会看到完整文件。
 * @param {{ outPath?: string }} [options]
 * @returns {Promise<string>} 实际写入路径
 */
export async function buildClient(options = {}) {
  const outPath = options.outPath ?? join(repositoryRoot, '.dsh-plugin/client.js')
  await mkdir(dirname(outPath), { recursive: true })
  const temporary = `${outPath}.tmp`
  await writeFile(temporary, await clientBundle(), 'utf8')
  await rename(temporary, outPath)
  return outPath
}

if (process.argv[1] !== undefined && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  buildClient()
    .then((path) => console.log(`built ${path}`))
    .catch((error) => {
      console.error(error)
      process.exit(1)
    })
}
